function dayOfYear(m: number, d: number): number {
  return Math.round((Date.UTC(2001, m - 1, d) - Date.UTC(2001, 0, 1)) / 86_400_000);
}

/** 오늘과 가장 가까운 지난(또는 오늘의) 사건. 같은 날이 여럿이면 해마다 돌아가며 고릅니다. */
export function spaceHistoryFor(date: Date): { item: SpaceDay; daysAgo: number } {
  const today = dayOfYear(date.getMonth() + 1, Math.min(date.getDate(), date.getMonth() === 1 ? 28 : 31));
  let bestAgo = 400;
  for (const item of SPACE_HISTORY) {
    const ago = (today - dayOfYear(item.m, item.d) + 365) % 365;
    if (ago < bestAgo) bestAgo = ago;
  }
  const same = SPACE_HISTORY.filter((item) => (today - dayOfYear(item.m, item.d) + 365) % 365 === bestAgo);
  return { item: same[date.getFullYear() % same.length], daysAgo: bestAgo };
}
